#!/usr/bin/env python3
"""按板确定性生成 AuroraOS 配置（autoconf.h / autoconf.cmake / autoconf.config）。

设计原则 —— 单一事实源 = Kconfig
=================================
配置值**只能**由 Kconfig（含 Kconfig.miband）推导而来。本脚本不硬编码任何
配置值，因此脚本与 Kconfig 之间不存在"两份真相"的漂移空间。

用法
----
    python scripts/genconfig.py --board <BOARD> --out <DIR>

    --board   目标板标识（lm3s6965-qb / miband8 / qemu_rv32_virt /
              nucleo_l031k6 / qemu_aarch64_virt / qemu_mps2_an500）。
              必须与 CMake -DBOARD= 传入值一致。
    --out     输出目录（一律使用 CMake 构建目录 ${CMAKE_BINARY_DIR}）。
    --config  可选：用户自定义 .config 路径（menuconfig 产物），叠加在板级
              默认之上。未指定时使用纯板级默认。

为什么不再"见 autoconf.h 存在就跳过"
----------------------------------
历史版本（见 DOCS/KNOWN_ISSUES.md 4b）把生成物写进被 git 跟踪的
config/autoconf.h，且检测到文件已存在即跳过重生成——完全不校验该文件属于
哪块板。后果是多块板共享同一路径，后构建的板被前一块板的配置"投毒"，
CMake 分支（读 autoconf.cmake）与 C 预处理（-include autoconf.h）可能看到
两套不同配置，且结果取决于构建顺序。

现方案从机制上消除陈旧可能：
  1. 生成物一律写进 --out（构建目录），不入库、不共享；
  2. 每次运行都完整重算（无"已存在则跳过"分支）；
  3. --board 强制选中对应 BOARD_* 符号，不依赖默认值；
  4. autoconf.h / autoconf.cmake / autoconf.config 三者同次运行产出，天然同源；
  5. autoconf.h 尾部内嵌板级一致性硬校验（见 _append_board_guard），把
     "误读陈旧/错板 autoconf.h"从静默错误升级为编译错误。

M0+ 等资源受限板的裁剪（无网络 / 无 Lua / 2 任务等）不是脚本私有知识，
而是 Kconfig 中 `default ... if BOARD_XXX` 表达的板级策略——单一事实源。
"""

import argparse
import os
import sys


BOARD_SYMBOLS = {
    "lm3s6965-qb": "BOARD_LM3S6965_QB",
    "miband8": "BOARD_MIBAND8",
    "qemu_rv32_virt": "BOARD_QEMU_RV32_VIRT",
    "nucleo_l031k6": "BOARD_NUCLEO_L031K6",
    "qemu_aarch64_virt": "BOARD_QEMU_AARCH64_VIRT",
    "qemu_mps2_an500": "BOARD_QEMU_MPS2_AN500",
}


def _append_board_guard(autoconf_path, board):
    """在 autoconf.h 末尾追加板级一致性硬校验。

    目的：把"误读了别的板/陈旧的 autoconf.h"从静默错误升级为编译硬错误。

    机制：genconfig.py 在此内嵌 AURORA_ACTUAL_BOARD 字符串字面量。
    CMake 通过 target_compile_definitions 注入 AURORA_EXPECT_BOARD="<board>"。
    下方 static_assert 比较两字符串长度与前缀——若 autoconf.h 属于另一块板，
    校验失败，编译中断。纯 C TU（boot/*.c）用 #if defined(__cplusplus) 旁路
    （C 无 static_assert），它们不读 Kconfig 特性开关，风险可接受。
    """
    with open(autoconf_path, "a", encoding="utf-8") as f:
        f.write("\n/* ---- Board consistency guard (generated by genconfig.py) ---- */\n")
        f.write("/* 若本文件被另一块板的构建误读（include 路径解析到陈旧 autoconf.h），\n")
        f.write(" * 下方 static_assert 触发编译错误，避免产出配置错乱的固件。\n")
        f.write(" * AURORA_EXPECT_BOARD 由 CMake target_compile_definitions 注入。\n")
        f.write(" * 历史事故见 DOCS/KNOWN_ISSUES.md 4b。 */\n")
        f.write(f'#define AURORA_ACTUAL_BOARD "{board}"\n')
        f.write("#ifdef AURORA_EXPECT_BOARD\n")
        f.write("#  ifdef __cplusplus\n")
        f.write("     static_assert(sizeof(AURORA_EXPECT_BOARD) == sizeof(AURORA_ACTUAL_BOARD),\n")
        f.write('         "AuroraOS config mismatch: autoconf.h was generated for a different board "\n')
        f.write('         "than -DAURORA_EXPECT_BOARD. A stale config/autoconf.h is being picked up — "\n')
        f.write('         "regenerate via scripts/genconfig.py into the build directory.");\n')
        f.write("#  endif /* __cplusplus */\n")
        f.write("#endif /* AURORA_EXPECT_BOARD */\n")


def _emit_cmake(kconf, cmake_path):
    """由 Kconfig 符号值生成 autoconf.cmake（供 CMake include() 消费）。

    与 autoconf.h 同源同次生成，保证 CMake 的 if(CONFIG_XXX) 分支与 C 预处理
    看到完全一致的配置。未启用的符号**不**输出 set()，使其在 CMake 中为空。
    """
    with open(cmake_path, "w", encoding="utf-8") as f:
        f.write("# Automatically generated by genconfig.py from Kconfig — DO NOT EDIT\n")
        f.write(f"# Board: {kconf.syms['BOARD'].str_value}\n")
        for sym in kconf.unique_defined_syms:
            if sym.type in (kconfiglib.BOOL, kconfiglib.TRISTATE):
                if sym.str_value == "y":
                    f.write(f'set(CONFIG_{sym.name} "y")\n')
                elif sym.str_value == "m":
                    f.write(f'set(CONFIG_{sym.name} "m")\n')
            elif sym.type == kconfiglib.STRING:
                f.write(f'set(CONFIG_{sym.name} "{sym.str_value}")\n')
            elif sym.type in (kconfiglib.INT, kconfiglib.HEX):
                f.write(f'set(CONFIG_{sym.name} {sym.str_value})\n')
    print(f"Generated {cmake_path}")


def main():
    global kconfiglib
    try:
        import kconfiglib
    except ImportError:
        print(
            "Error: kconfiglib not found. Please install it using 'pip install kconfiglib'",
            file=sys.stderr,
        )
        return 1

    parser = argparse.ArgumentParser(
        description="Generate per-board AuroraOS config artifacts from Kconfig (single source of truth)."
    )
    parser.add_argument("--board", required=True, choices=sorted(BOARD_SYMBOLS),
                        help="Target board (must match CMake -DBOARD=)")
    parser.add_argument("--out", required=True,
                        help="Output directory (use the CMake build dir)")
    parser.add_argument("--config", default=None,
                        help="Optional user .config to layer on top of board defaults")
    args = parser.parse_args()

    repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    os.chdir(repo_root)

    if not os.path.isfile("Kconfig"):
        print("Error: Kconfig not found in repo root", file=sys.stderr)
        return 1

    os.makedirs(args.out, exist_ok=True)

    kconf = kconfiglib.Kconfig("Kconfig")

    # 1) 强制选中目标板。不依赖 Kconfig 默认板，避免 --board 与默认值漂移。
    board_sym_name = BOARD_SYMBOLS[args.board]
    kconf.syms[board_sym_name].set_value(2)  # 2 == 'y'

    # 2) 可选叠加用户 menuconfig 自定义（仅 .config 中显式给出的符号覆盖默认）。
    #    replace=False 是必须的：kconfiglib 默认 replace=True 会先把所有符号重置
    #    为 Kconfig 默认值，连上面刚强制选中的 BOARD_* 一起丢掉，导致非默认板的
    #    overlay 直接报 "CONFIG_BOARD 与 --board 不一致"。叠加语义应当是"只覆盖
    #    文件里显式出现的符号"，其余沿用板级默认。
    if args.config:
        if not os.path.isfile(args.config):
            print(f"Error: --config file not found: {args.config}", file=sys.stderr)
            return 1
        kconf.load_config(args.config, replace=False)

    # 3) 校验：Kconfig 解析出的 CONFIG_BOARD 必须与 --board 一致，
    #    否则说明 BOARD 字符串默认与 BOARD_* 符号映射出现漂移。
    resolved_board = kconf.syms["BOARD"].str_value
    if resolved_board != args.board:
        print(
            f"Error: Kconfig resolves CONFIG_BOARD={resolved_board!r} but --board={args.board!r}. "
            f"The BOARD string defaults in Kconfig are out of sync with {board_sym_name}.",
            file=sys.stderr,
        )
        return 1

    # 4) 三件套同次生成 —— 天然同源，不存在"其中一份陈旧"。
    autoconf_path = os.path.join(args.out, "autoconf.h")
    kconf.write_autoconf(autoconf_path)
    _append_board_guard(autoconf_path, args.board)
    print(f"Generated {autoconf_path}")

    # 同时在输出目录下提供 config/autoconf.h，供源码中 #include "config/autoconf.h" 寻址
    config_out = os.path.join(args.out, "config")
    os.makedirs(config_out, exist_ok=True)
    import shutil
    shutil.copy2(autoconf_path, os.path.join(config_out, "autoconf.h"))

    cmake_path = os.path.join(args.out, "autoconf.cmake")
    _emit_cmake(kconf, cmake_path)

    dotconfig_path = os.path.join(args.out, "autoconf.config")
    kconf.write_config(dotconfig_path)
    print(f"Generated {dotconfig_path}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
